def stable_listener_rows(tcp,udp,xray_ports):
 rows=[]
 for line in tcp.splitlines():
  f=line.split()
  if len(f)<5:raise RuntimeError("invalid TCP inventory")
  rows.append(("tcp",f[0],f[3],f[4]))
 for line in udp.splitlines():
  f=line.split()
  if len(f)<5:raise RuntimeError("invalid UDP inventory")
  port=int(f[3].rsplit(":",1)[1])
  owner=" ".join(f[5:])
  # These are xray's per-client outbound UDP sockets, not configured inbounds.
  if "xray-linux-" in owner and port not in xray_ports:continue
  owners=tuple(re.findall(r'\("([^"]+)",pid=(\d+)',owner))
  rows.append(("udp",f[0],f[3],f[4],owners))
 return sorted(rows)

def listeners():
 if not guard.clean_path(XRAY_CONFIG):raise RuntimeError("unsafe xray config")
 raw=XRAY_CONFIG.read_bytes();config=json.loads(raw)
 ports=set()
 for row in config.get("inbounds",[]):
  p=str(row["port"])
  for group in p.split(","):
   if re.fullmatch(r"\d+",group):ports.add(int(group))
   elif re.fullmatch(r"\d+-\d+",group):
    lo,hi=map(int,group.split("-"))
    if not 0<lo<=hi<65536:raise RuntimeError("unknown xray port")
    ports.update(range(lo,hi+1))
   else:raise RuntimeError("unknown xray port")
 return stable_listener_rows(checked(["ss","-H","-lnt"]),checked(["ss","-H","-lnup"]),ports),hashlib.sha256(raw).hexdigest()


def safe_generated(p):
 """Allow only internal symlinks in exact regenerable dependency trees."""
 try:
  if not guard.clean_path(p) or not p.is_dir():return False
  if any(x==p or p in x.parents for x in guard.mount_points()):return False
  root=p.lstat();nodes=[p]
  for base,dirs,files in os.walk(p,followlinks=False):
   nodes.extend(pathlib.Path(base)/n for n in dirs+files)
   if len(nodes)>30000:return False
  links={}
  for n in nodes:
   st=n.lstat()
   if stat.S_ISREG(st.st_mode):links[(st.st_dev,st.st_ino)]=links.get((st.st_dev,st.st_ino),0)+1
  for n in nodes:
   st=n.lstat()
   if st.st_dev!=root.st_dev or max(st.st_mtime,st.st_ctime)>=guard.CUTOFF:return False
   if stat.S_ISLNK(st.st_mode):
    resolved=n.resolve(strict=True)
    if p not in resolved.parents:return False
   elif not (stat.S_ISDIR(st.st_mode) or stat.S_ISREG(st.st_mode)):return False
   elif stat.S_ISREG(st.st_mode) and st.st_nlink!=links[(st.st_dev,st.st_ino)]:return False
  return not guard.open_file(p)
 except (OSError,RuntimeError):return False

def anchored_remove(p):
 before=p.lstat();fd=guard.parent_fd(p)
 try:
  current=os.stat(p.name,dir_fd=fd,follow_symlinks=False)
  if (before.st_dev,before.st_ino,before.st_mtime_ns,before.st_ctime_ns)!=(current.st_dev,current.st_ino,current.st_mtime_ns,current.st_ctime_ns):return "SKIP_CHANGED"
  if stat.S_ISDIR(current.st_mode):
   if not shutil.rmtree.avoids_symlink_attacks:return "SKIP_PLATFORM"
   if sys.version_info>=(3,11):shutil.rmtree(p.name,dir_fd=fd)
   else:
    cwd=os.open(".",os.O_RDONLY|os.O_DIRECTORY)
    try:os.fchdir(fd);shutil.rmtree(p.name)
    finally:os.fchdir(cwd);os.close(cwd)
  else:os.unlink(p.name,dir_fd=fd)
 finally:os.close(fd)
 return "REMOVED"


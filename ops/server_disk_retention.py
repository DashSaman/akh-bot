def execute(kind,p):
 if kind=="cache":return remove_cache(p)
 if kind=="growth-export":
  if (kind,p) not in growth_candidates():return "SKIP_PROTECTED"
  return anchored_remove(p) if guard.safe_tree(p) else "SKIP_SAFETY"
 if kind=="mysql-binlogs":return mysql_archive_purge()
 if kind=="rasteh":
  return "OK" if guard.command([sys.executable,str(p),"--apply"],600).returncode==0 else "FAILED_RASTEH"
 if kind=="old-image":
  old=guard.IMAGE_KEEP
  try:guard.IMAGE_KEEP={"pv-growth-app":2};return guard.apply(kind,p)
  finally:guard.IMAGE_KEEP=old
 scoped=(kind=="rotated-log" and log_allowed(p)) or (kind=="backup-archive" and p in backup_retention_candidates()) or (kind=="audit" and p.parent==REPORT_ROOT and bool(re.fullmatch(r"run-\d{8}T\d{6}Z-\d+\.jsonl",p.name)))
 if not scoped:return "SKIP_SCOPE"
 if not guard.safe_tree(p):return "SKIP_SAFETY"
 return anchored_remove(p)

def main(argv=None):
 parser=argparse.ArgumentParser();parser.add_argument("--apply",action="store_true");args=parser.parse_args(argv)
 fd=guard.parent_fd(LOCK_PATH)
 try:lock=os.open(LOCK_PATH.name,os.O_CREAT|os.O_RDWR|os.O_NOFOLLOW,0o600,dir_fd=fd)
 finally:os.close(fd)
 try:
  st=os.fstat(lock)
  if not stat.S_ISREG(st.st_mode) or st.st_nlink!=1:raise RuntimeError("unsafe lock")
  try:fcntl.flock(lock,fcntl.LOCK_EX|fcntl.LOCK_NB)
  except BlockingIOError:print('{"status":"SKIP_LOCKED"}');return 0
  before=snapshot()
  report={"mode":"APPLY" if args.apply else "DRY_RUN","before":before,"actions":[]}
  if args.apply:audit({"phase":"START",**report})
  if not before["ok"]:
   report["status"]="SKIP_UNHEALTHY"
   if args.apply:audit({"phase":"FINISH",**report})
   print(json.dumps(report));return 2
  planned=plans();report["planned"]=[(k,str(p)) for k,p in planned]
  failed=False
  if args.apply:
   for kind,p in planned:
    now=snapshot()
    if not now["ok"] or now["identity"]!=before["identity"]:
     report["actions"].append({"status":"HALTED_HEALTH_OR_DEPLOYMENT_CHANGE","errors":now["errors"]});failed=True;break
    audit({"phase":"ACTION_START","kind":kind,"path":str(p)})
    try:status=execute(kind,p)
    except Exception as e:status="FAILED:"+type(e).__name__
    row={"kind":kind,"path":str(p),"status":status};report["actions"].append(row);audit({"phase":"ACTION",**row})
    if status.startswith("FAILED"):failed=True;break
  after=snapshot() if args.apply else before
  report.update(after=after,net_free_delta_bytes=after["free_bytes"]-before["free_bytes"],available_percent=round(100*after["free_bytes"]/after["total_bytes"],2),target_percent=50)
  failed=failed or not after["ok"] or after["identity"]!=before["identity"]
  report["status"]="ATTENTION" if failed else "OK"
  if report["available_percent"]<50:report["capacity_warning"]="Below 50%; protected resources are never removed to force target."
  if args.apply:audit({"phase":"FINISH",**report})
  print(json.dumps(report))
  return 2 if failed else 0
 finally:os.close(lock)

if __name__=="__main__":sys.exit(main())

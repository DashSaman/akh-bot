def sql(query):return checked(["mysql","--batch","--skip-column-names","-e",query],60)

def mysql_local_only():
 # Do not purge on a replica, with consumers, or with potential remote replica users.
 if sql("SHOW REPLICAS") or sql("SHOW REPLICA STATUS"):return False
 if sql("SELECT ID FROM information_schema.PROCESSLIST WHERE COMMAND LIKE 'Binlog Dump%'"):return False
 return not sql("SELECT Host FROM mysql.user WHERE Repl_slave_priv='Y' AND Host NOT IN ('localhost','127.0.0.1','::1')")

def binlog_old(name):
 if not BINLOG_RE.fullmatch(name):return False
 p=BINLOG_ROOT/name
 return guard.safe_tree(p)

def old_binlogs():
 rows=[(r.split()[0],int(r.split()[1])) for r in sql("SHOW BINARY LOGS").splitlines()]
 old=[]
 for name,size in rows[:-1]:
  if not binlog_old(name):break
  old.append((name,size))
 return old

def hash_stream(f):
 h=hashlib.sha256()
 for b in iter(lambda:f.read(1024*1024),b""):h.update(b)
 return h.hexdigest()

def mysql_archive_purge():
 if not mysql_local_only():return "SKIP_REPLICATION"
 baseline=snapshot()
 if not baseline["ok"]:return "SKIP_UNHEALTHY"
 old=old_binlogs()
 if not old:return "SKIP_NO_OLD_LOGS"
 # Enough room for incompressible archives + fresh SQL dump; preserve 1GB reserve.
 if shutil.disk_usage("/").free<sum(x[1] for x in old)+1024**3:return "SKIP_HEADROOM"
 secure_dir(BACKUP_ROOT)
 dump=BACKUP_ROOT/("mysql-"+RUN_ID+".sql.gz")
 args=["mysqldump","--single-transaction","--skip-lock-tables","--routines","--events","--triggers","--all-databases","--set-gtid-purged=OFF","--no-tablespaces"]
 fd=os.open(dump,os.O_CREAT|os.O_EXCL|os.O_WRONLY|os.O_NOFOLLOW,0o600)
 with os.fdopen(fd,"wb") as raw:
  with gzip.GzipFile(fileobj=raw,mode="wb") as z:
   proc=subprocess.Popen(args,stdout=subprocess.PIPE,stderr=subprocess.DEVNULL)
   try:
    for b in iter(lambda:proc.stdout.read(1024*1024),b""):z.write(b)
   finally:proc.stdout.close()
   if proc.wait(timeout=300):raise RuntimeError("backup failed")
  raw.flush();os.fsync(raw.fileno())
 with gzip.open(dump,"rb") as f:
  content_bytes=0
  for b in iter(lambda:f.read(1024*1024),b""):content_bytes+=len(b)
 if content_bytes<10000:raise RuntimeError("backup too small")
 with dump.open("rb") as f:dump_sha=hash_stream(f)
 private_write(dump.with_suffix(".verified.json"),json.dumps({"complete":True,"sha256":dump_sha}).encode())
 archive=BACKUP_ROOT/("binlogs-"+RUN_ID+".tar.gz")
 manifest=[]
 fd=os.open(archive,os.O_CREAT|os.O_EXCL|os.O_WRONLY|os.O_NOFOLLOW,0o600)
 with os.fdopen(fd,"wb") as raw:
  with tarfile.open(fileobj=raw,mode="w:gz") as t:
   for name,size in old:
    p=BINLOG_ROOT/name
    if not binlog_old(name) or p.stat().st_size!=size:raise RuntimeError("binlog changed")
    with p.open("rb") as f:sha=hash_stream(f)
    st=p.stat()
    manifest.append({"name":name,"size":size,"sha256":sha,"inode":st.st_ino,"mtime_ns":st.st_mtime_ns,"ctime_ns":st.st_ctime_ns})
    t.add(p,arcname=name,recursive=False)
  raw.flush();os.fsync(raw.fileno())
 with tarfile.open(archive,"r:gz") as t:
  if [x.name for x in t.getmembers()]!=[x[0] for x in old]:raise RuntimeError("archive members changed")
  for x in manifest:
   with t.extractfile(x["name"]) as f:
    if hash_stream(f)!=x["sha256"]:raise RuntimeError("archive checksum failed")
 private_write(archive.with_suffix(".manifest.json"),json.dumps({"logs":manifest,"dump":str(dump),"verified":True}).encode())
 current=snapshot()
 if not current["ok"] or current["identity"]!=baseline["identity"]:return "SKIP_HEALTH_OR_DEPLOYMENT_CHANGE"
 if not mysql_local_only() or old_binlogs()!=old:return "SKIP_CHANGED"
 for x in manifest:
  st=(BINLOG_ROOT/x["name"]).stat()
  if (st.st_ino,st.st_mtime_ns,st.st_ctime_ns)!=(x["inode"],x["mtime_ns"],x["ctime_ns"]):return "SKIP_CHANGED"
 rows=[r.split()[0] for r in sql("SHOW BINARY LOGS").splitlines()]
 next_name=rows[len(old)]
 if not BINLOG_RE.fullmatch(next_name):raise RuntimeError("invalid log name")
 audit({"phase":"VERIFIED_BINLOG_ARCHIVE","archive":str(archive),"backup":str(dump),"purge_before":next_name})
 sql("PURGE BINARY LOGS TO '"+next_name+"'")
 return "ARCHIVED_AND_PURGED"

def backup_retention_candidates():
 if not guard.clean_path(BACKUP_ROOT) or not BACKUP_ROOT.is_dir():return []
 result=[]
 for pattern,days in (("mysql-*.sql.gz",5),("binlogs-*.tar.gz",30)):
  files=sorted((p for p in BACKUP_ROOT.glob(pattern) if guard.clean_path(p) and p.is_file() and (p.with_suffix(".verified.json") if pattern.startswith("mysql") else p.with_suffix(".manifest.json")).is_file()),key=lambda p:p.stat().st_mtime,reverse=True)
  # Keep the last two successfully verifiable archives, fail closed otherwise.
  try:
   for p in files[:2]:
    with gzip.open(p,"rb") as f:
     for _ in iter(lambda:f.read(1024*1024),b""):pass
  except (OSError,EOFError):continue
  if len(files)<2:continue
  for p in files[2:]:
   if p.stat().st_mtime<time.time()-days*86400 and guard.safe_tree(p):result.append(p)
 return result


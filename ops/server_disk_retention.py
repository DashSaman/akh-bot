def growth_candidates():
 if not guard.clean_path(GROWTH_ROOT) or not GROWTH_ROOT.is_dir():return []
 dirs=[p for p in GROWTH_ROOT.iterdir() if re.fullmatch(r"[0-9a-f]{40}",p.name) and guard.clean_path(p) and p.is_dir()]
 dirs.sort(key=lambda p:p.stat().st_mtime,reverse=True)
 keep={p.name for p in dirs[:2]}
 containers=guard.container_inventory();used={x["Image"] for x in containers}
 for x in containers:
  ref=x["Config"]["Image"]
  if ref.startswith("pv-growth-app:"):
   tag=ref.partition(":")[2]
   if not re.fullmatch(r"[0-9a-f]{40}",tag):return []
   keep.add(tag)
 entries=[]
 for row in checked(["docker","image","ls","--format","{{.Repository}}|{{.Tag}}"]).splitlines():
  repo,tag=row.split("|",1)
  if repo!="pv-growth-app":continue
  if not re.fullmatch(r"[0-9a-f]{40}",tag):return []

def mysql_fixture(tmp_path,monkeypatch,backup_rc=0):
 import io
 monkeypatch.setattr(m,'BINLOG_ROOT',tmp_path/'mysql');m.BINLOG_ROOT.mkdir()
 monkeypatch.setattr(m,'BACKUP_ROOT',tmp_path/'backups')
 monkeypatch.setattr(m.guard,'CUTOFF',float('inf'))
 monkeypatch.setattr(m.guard,'open_file',lambda p:False)
 monkeypatch.setattr(m.guard,'mount_points',lambda:set())
 for i in range(1,4):(m.BINLOG_ROOT/('binlog.%06d'%i)).write_bytes((b'original-history-'+str(i).encode())*100)
 queries=[]
 def sql(q):
  queries.append(q)
  if q=='SHOW BINARY LOGS':
   return '\n'.join(p.name+'\t'+str(p.stat().st_size) for p in sorted(m.BINLOG_ROOT.iterdir()))
  return ''
 monkeypatch.setattr(m,'sql',sql)
 monkeypatch.setattr(m,'snapshot',lambda:{'ok':True,'identity':{},'errors':[]})
 monkeypatch.setattr(m,'audit',lambda x:None)
 usage=type('Usage',(),{'free':10*1024**3})()
 monkeypatch.setattr(m.shutil,'disk_usage',lambda p:usage)
 class Process:
  def __init__(self,*a,**k):self.stdout=io.BytesIO(b'-- complete dump\n'+b'x'*20000)
  def wait(self,**k):return backup_rc
 monkeypatch.setattr(m.subprocess,'Popen',Process)
 return queries

def test_mysql_purge_requires_verified_archive_and_backup(tmp_path,monkeypatch):
 import tarfile
 queries=mysql_fixture(tmp_path,monkeypatch)
 assert m.mysql_archive_purge()=='ARCHIVED_AND_PURGED'
 assert queries[-1]=="PURGE BINARY LOGS TO 'binlog.000003'"
 with tarfile.open(next(m.BACKUP_ROOT.glob('*.tar.gz')),'r:gz') as t:
  assert [x.name for x in t.getmembers()]==['binlog.000001','binlog.000002']
  assert t.extractfile('binlog.000001').read()==(m.BINLOG_ROOT/'binlog.000001').read_bytes()
 assert len(list(m.BACKUP_ROOT.glob('*.verified.json')))==1

def test_mysql_failed_backup_never_purges(tmp_path,monkeypatch):
 import pytest
 queries=mysql_fixture(tmp_path,monkeypatch,1)
 with pytest.raises(RuntimeError,match='backup failed'):m.mysql_archive_purge()
 assert not any(q.startswith('PURGE') for q in queries)
 assert not list(m.BACKUP_ROOT.glob('*.verified.json'))

def test_mysql_archive_checksum_failure_never_purges(tmp_path,monkeypatch):
 import pytest
 queries=mysql_fixture(tmp_path,monkeypatch)
 real=m.hash_stream;calls=[0]
 def wrong_on_verify(f):
  calls[0]+=1
  return 'wrong' if calls[0]==4 else real(f)
 monkeypatch.setattr(m,'hash_stream',wrong_on_verify)
 with pytest.raises(RuntimeError,match='archive checksum'):m.mysql_archive_purge()
 assert not any(q.startswith('PURGE') for q in queries)

def test_growth_exports_keep_runtime_rollback_and_unknown_files(tmp_path,monkeypatch):
 monkeypatch.setattr(m,'GROWTH_ROOT',tmp_path)
 monkeypatch.setattr(m.guard,'CUTOFF',float('inf'))
 monkeypatch.setattr(m.guard,'open_file',lambda p:False)
 monkeypatch.setattr(m.guard,'mount_points',lambda:set())
 tags=['a'*40,'b'*40,'c'*40]
 for tag in tags:
  d=tmp_path/tag;d.mkdir();(d/'delta.json').write_text('{}');(d/('pv-growth-app-'+tag+'.tar')).write_text('old export');(d/'customer.sql').write_text('DB')
 # Explicit current and unused rollback protected even when older dir mtime.
 monkeypatch.setattr(m.guard,'container_inventory',lambda:[{'Image':'current','Config':{'Image':'pv-growth-app:'+tags[0]}}])
 def checked(args,*rest):
  if args[:3]==['docker','image','ls']:return '\n'.join('pv-growth-app|'+tag for tag in tags[:2])
  return ('current' if args[-1].endswith(tags[0]) else 'rollback')+'|2026-01-01T00:00:00Z'
 monkeypatch.setattr(m,'checked',checked)
 # Newest two folders need not be the runtime dirs; still never delete them.
 for i,tag in enumerate(tags):os.utime(tmp_path/tag,(100-i,100-i))
 assert m.growth_candidates()==[('growth-export',tmp_path/tags[2]/('pv-growth-app-'+tags[2]+'.tar'))]
 assert m.execute('growth-export',tmp_path/tags[0]/('pv-growth-app-'+tags[0]+'.tar'))=='SKIP_PROTECTED'
 assert m.execute('growth-export',tmp_path/tags[2]/'customer.sql')=='SKIP_PROTECTED'

